/** Calendar-date arithmetic in UTC, for the governance registers' derived due and expiry dates. */

/** The date plus whole calendar months, clamped to the end of a shorter month (Jan 31 + 1 → Feb 28). */
export function addMonthsUtc(date: Date, months: number): Date {
  const year = date.getUTCFullYear();
  const month = date.getUTCMonth() + months;
  const lastDay = new Date(Date.UTC(year, month + 1, 0)).getUTCDate();
  return new Date(Date.UTC(year, month, Math.min(date.getUTCDate(), lastDay)));
}

/** The date plus whole days. */
export function addDaysUtc(date: Date, days: number): Date {
  return new Date(date.getTime() + days * 24 * 60 * 60 * 1000);
}
